const { contextBridge, ipcRenderer } = require('electron');
const subscribe = channel => callback => { const listener = (_, state) => callback(state); ipcRenderer.on(channel, listener); return () => ipcRenderer.removeListener(channel, listener); };
contextBridge.exposeInMainWorld('arena', {
  engines: () => ipcRenderer.invoke('engines:list'),
  addEngine: () => ipcRenderer.invoke('engines:add'),
  importAnchors: () => ipcRenderer.invoke('engines:importAnchors'),
  updateEngine: engine => ipcRenderer.invoke('engines:update', engine),
  removeEngine: id => ipcRenderer.invoke('engines:remove', id),
  chooseLogo: id => ipcRenderer.invoke('engines:logo', id),
  start: config => ipcRenderer.invoke('match:start', config),
  pause: () => ipcRenderer.invoke('match:pause'),
  stop: () => ipcRenderer.invoke('match:stop'),
  history: () => ipcRenderer.invoke('history:list'),
  exportPgn: text => ipcRenderer.invoke('pgn:export', text),
  exportResultImage: data => ipcRenderer.invoke('result:image', data),
  onState: subscribe('match:state'),
  systemInfo: () => ipcRenderer.invoke('system:info'),
  chooseBook: () => ipcRenderer.invoke('book:choose'),
  chooseFolder: title => ipcRenderer.invoke('folder:choose', title),
  gauntlet: {
    start: config => ipcRenderer.invoke('gauntlet:start', config),
    current: () => ipcRenderer.invoke('gauntlet:current'),
    pause: () => ipcRenderer.invoke('gauntlet:pause'),
    stop: () => ipcRenderer.invoke('gauntlet:stop'),
    list: () => ipcRenderer.invoke('gauntlet:list'),
    exportPgn: id => ipcRenderer.invoke('gauntlet:export', id),
    onState: subscribe('gauntlet:state'),
  },
  fastchess: {
    status: () => ipcRenderer.invoke('fastchess:status'),
    locate: () => ipcRenderer.invoke('fastchess:locate'),
    start: config => ipcRenderer.invoke('fastchess:start', config),
    current: () => ipcRenderer.invoke('fastchess:current'),
    stop: () => ipcRenderer.invoke('fastchess:stop'),
    list: () => ipcRenderer.invoke('fastchess:list'),
    exportPgn: id => ipcRenderer.invoke('fastchess:export', id),
    onState: subscribe('fastchess:state'),
  },
});
